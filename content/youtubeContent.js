/**
 * FX English - YouTube Content Script
 * Headless content worker: detects video & caption tracks, communicates with
 * player bridge in MAIN world, and serves subtitle data directly to Extension Popup and Studio.
 * Zero in-page popup / widget overlays on the video player.
 */

(function () {
  'use strict';

  if (window.__fxYoutubeContentInjected) return;
  window.__fxYoutubeContentInjected = true;

  // Thoroughly purge and suppress any in-page floating popups or widgets (both FX and AF legacy)
  const purgeInPageOverlays = () => {
    const selectors = [
      '#fx-youtube-widget',
      '#af-youtube-widget',
      '#fx-netflix-widget',
      '#af-netflix-widget',
      '.af-widget-pill',
      '.fx-widget-pill',
      '#fx-youtube-modal-backdrop',
      '#af-modal-backdrop',
      '#fx-netflix-modal-backdrop'
    ];
    selectors.forEach((sel) => {
      document.querySelectorAll(sel).forEach((el) => {
        try { el.remove(); } catch (e) {}
      });
    });
  };

  try {
    purgeInPageOverlays();

    // Inject CSS rule to guarantee elements are completely hidden and unclickable
    if (!document.getElementById('fx-hide-all-overlays')) {
      const hideStyle = document.createElement('style');
      hideStyle.id = 'fx-hide-all-overlays';
      hideStyle.textContent = `
        #fx-youtube-widget, #af-youtube-widget,
        #fx-netflix-widget, #af-netflix-widget,
        .af-widget-pill, .fx-widget-pill,
        #fx-youtube-modal-backdrop, #af-modal-backdrop,
        #fx-netflix-modal-backdrop {
          display: none !important;
          visibility: hidden !important;
          opacity: 0 !important;
          pointer-events: none !important;
          width: 0 !important;
          height: 0 !important;
          position: absolute !important;
          top: -9999px !important;
          left: -9999px !important;
        }
      `;
      (document.head || document.documentElement).appendChild(hideStyle);
    }

    // Watch for dynamic element insertions and remove immediately
    const observer = new MutationObserver(() => {
      purgeInPageOverlays();
    });
    if (document.documentElement || document.body) {
      observer.observe(document.documentElement || document.body, { childList: true, subtree: true });
    }
  } catch (e) {}

  const PARSER = (typeof APP_SUBTITLE_PARSER !== 'undefined') ? APP_SUBTITLE_PARSER : null;

  const YouTubeManager = {
    tracks: [],
    selectedTrack: null,
    videoTitle: '',
    currentVideoId: '',
    cues: [],
    isLoadingSubtitles: false,

    init() {
      this.listenBridge();
      this.checkVideoChange();
      this.pollUrlChanges();
      // Prompt injected script for caption tracks
      window.dispatchEvent(new CustomEvent('fx_youtube_request_info'));
    },

    getVideoId() {
      try {
        const u = new URL(window.location.href);
        if (u.searchParams.has('v')) return u.searchParams.get('v');
        const match = u.pathname.match(/\/shorts\/([a-zA-Z0-9_-]+)/);
        if (match) return match[1];
        const liveMatch = u.pathname.match(/\/live\/([a-zA-Z0-9_-]+)/);
        if (liveMatch) return liveMatch[1];
        const embedMatch = u.pathname.match(/\/embed\/([a-zA-Z0-9_-]+)/);
        if (embedMatch) return embedMatch[1];
      } catch (e) {}
      return null;
    },

    getTitle() {
      let t = this.videoTitle;
      if (!t || t.toLowerCase() === 'youtube' || t === 'YouTube Video') {
        const titleEl = document.querySelector('h1.ytd-watch-metadata yt-formatted-string, #title h1, h1.title, ytd-watch-metadata #title, #above-the-fold #title');
        if (titleEl && titleEl.textContent && titleEl.textContent.trim()) {
          t = titleEl.textContent.trim();
        }
      }
      if (!t || t.toLowerCase() === 'youtube' || t === 'YouTube Video') {
        const docClean = (document.title || '').replace(/\s*-\s*YouTube.*$/i, '').trim();
        if (docClean && docClean.toLowerCase() !== 'youtube') {
          t = docClean;
        }
      }
      return t || 'YouTube Video';
    },

    listenBridge() {
      // Injected MAIN world script bridge event
      window.addEventListener('fx_youtube_bridge_event', (e) => {
        const { type, data } = e.detail || {};
        if (type === 'youtube_tracks_ready' && data) {
          if (data.title && !this.videoTitle) this.videoTitle = data.title;
          if (Array.isArray(data.tracks) && data.tracks.length > 0) {
            this.tracks = data.tracks;
            const enTrack = this.tracks.find(t => t.isEnglish && !t.isAutoGenerated) ||
                            this.tracks.find(t => t.isEnglish);
            this.selectedTrack = enTrack || this.tracks[0];
          }
        }
      });
    },

    checkVideoChange() {
      const vid = this.getVideoId();
      if (!vid) return;

      if (vid !== this.currentVideoId) {
        this.currentVideoId = vid;
        this.cues = [];
        this.tracks = [];
        this.selectedTrack = null;
        this.videoTitle = '';

        // Request track metadata from MAIN world injected script
        window.dispatchEvent(new CustomEvent('fx_youtube_request_info'));
        setTimeout(() => {
          window.dispatchEvent(new CustomEvent('fx_youtube_request_info'));
        }, 1200);
      }
    },

    pollUrlChanges() {
      let lastUrl = window.location.href;
      setInterval(() => {
        if (window.location.href !== lastUrl) {
          lastUrl = window.location.href;
          this.checkVideoChange();
        }
      }, 1000);

      window.addEventListener('yt-navigate-finish', () => {
        setTimeout(() => this.checkVideoChange(), 600);
      });
    },

    getTranscriptFromDOM() {
      try {
        const segments = document.querySelectorAll('ytd-transcript-segment-renderer');
        if (segments && segments.length > 0) {
          const cues = [];
          segments.forEach((seg, idx) => {
            const timeEl = seg.querySelector('.segment-start-offset');
            const textEl = seg.querySelector('.segment-text');
            const timeStr = timeEl ? timeEl.textContent.trim() : '00:00';
            const text = textEl ? textEl.textContent.trim() : '';
            if (!text) return;

            const parts = timeStr.split(':').map(Number);
            let sec = 0;
            if (parts.length === 2) sec = parts[0] * 60 + parts[1];
            else if (parts.length === 3) sec = parts[0] * 3600 + parts[1] * 60 + parts[2];

            cues.push({
              index: cues.length + 1,
              start: PARSER ? PARSER.secondsToTimestamp(sec, false) : `00:${timeStr}.000`,
              end: PARSER ? PARSER.secondsToTimestamp(sec + 3, false) : `00:${timeStr}.000`,
              startSec: sec,
              endSec: sec + 3,
              text: text,
              cleanText: PARSER ? PARSER.cleanCueText(text) : text
            });
          });
          if (cues.length > 0) return cues;
        }
      } catch (e) {}
      return null;
    },

    async fetchSubtitles(forceTrackIndex = null) {
      if (this.cues.length > 0 && forceTrackIndex === null) {
        return this.cues;
      }

      if (typeof forceTrackIndex === 'number' && this.tracks[forceTrackIndex]) {
        this.selectedTrack = this.tracks[forceTrackIndex];
      }

      // If tracks list is not yet populated, try requesting again
      if (!this.selectedTrack && (!this.tracks || this.tracks.length === 0)) {
        window.dispatchEvent(new CustomEvent('fx_youtube_request_info'));
        await new Promise((resolve) => setTimeout(resolve, 800));
      }

      if (!this.selectedTrack && this.tracks && this.tracks.length > 0) {
        this.selectedTrack = this.tracks.find(t => t.isEnglish && !t.isAutoGenerated) ||
                            this.tracks.find(t => t.isEnglish) ||
                            this.tracks[0];
      }

      // Check DOM transcript fallback
      const domCues = this.getTranscriptFromDOM();
      if (domCues && domCues.length > 0 && (!this.selectedTrack || !this.selectedTrack.baseUrl)) {
        this.cues = domCues;
        return this.cues;
      }

      if (!this.selectedTrack || !this.selectedTrack.baseUrl) {
        throw new Error('Video này không có phụ đề tiếng Anh (hoặc CC chưa được bật). Vui lòng chọn video có biểu tượng CC trên YouTube.');
      }

      this.isLoadingSubtitles = true;

      try {
        const rawText = await this.fetchTimedText(this.selectedTrack.baseUrl, this.selectedTrack.language);
        this.isLoadingSubtitles = false;

        if (rawText === '__DOM_TRANSCRIPT__' && this.cues && this.cues.length > 0) {
          return this.cues;
        }

        if (!rawText || rawText.trim().length === 0) {
          const fallbackDom = this.getTranscriptFromDOM();
          if (fallbackDom && fallbackDom.length > 0) {
            this.cues = fallbackDom;
            return this.cues;
          }
          throw new Error('Không nhận được nội dung phụ đề từ YouTube. Hãy đảm bảo bạn đã bấm bật biểu tượng [CC] trên video rồi thử lại.');
        }

        const cues = PARSER ? PARSER.parse(rawText) : [];
        if (!cues || cues.length === 0) {
          const fallbackDom = this.getTranscriptFromDOM();
          if (fallbackDom && fallbackDom.length > 0) {
            this.cues = fallbackDom;
            return this.cues;
          }
          throw new Error('Không phân tích được nội dung phụ đề từ video này.');
        }

        this.cues = cues;
        return this.cues;
      } catch (err) {
        this.isLoadingSubtitles = false;
        throw err;
      }
    },

    fetchTimedText(url, lang = 'en') {
      return new Promise((resolve, reject) => {
        const requestId = 'req_' + Date.now() + '_' + Math.random().toString(36).slice(2, 8);
        let resolved = false;

        // Listener for MAIN world response
        const onResponse = (e) => {
          const { type, data } = e.detail || {};
          if (type === 'youtube_subtitles_text_ready' && data && (!data.requestId || data.requestId === requestId)) {
            window.removeEventListener('fx_youtube_bridge_event', onResponse);
            resolved = true;
            if (data.success && data.text) {
              resolve(data.text);
            } else {
              fallbackFetch(data.error);
            }
          }
        };

        window.addEventListener('fx_youtube_bridge_event', onResponse);

        // Dispatch to MAIN world with url and language code
        window.dispatchEvent(new CustomEvent('fx_youtube_fetch_timedtext', {
          detail: { url, lang, requestId }
        }));

        // Timeout fallback
        const timer = setTimeout(() => {
          if (!resolved) {
            window.removeEventListener('fx_youtube_bridge_event', onResponse);
            fallbackFetch();
          }
        }, 4000);

        const fallbackFetch = async (prevError) => {
          clearTimeout(timer);
          try {
            // 1. Direct fetch from content script
            const resp = await fetch(url, { credentials: 'include' });
            if (resp.ok) {
              const text = await resp.text();
              if (text && text.trim().length > 20) {
                return resolve(text);
              }
            }
          } catch (e) {}

          // 2. Check DOM transcript
          const domTranscript = this.getTranscriptFromDOM();
          if (domTranscript && domTranscript.length > 0) {
            this.cues = domTranscript;
            return resolve('__DOM_TRANSCRIPT__');
          }

          // 3. Fallback via background script
          try {
            chrome.runtime.sendMessage({ action: 'fetch_external_url', url }, (fb) => {
              if (fb && fb.success && fb.text && fb.text.trim().length > 20) {
                resolve(fb.text);
              } else {
                reject(new Error(prevError || 'YouTube không trả về nội dung phụ đề. Vui lòng bấm bật biểu tượng [CC] trên video rồi thử lại.'));
              }
            });
          } catch (err) {
            reject(new Error(prevError || 'Không thể tải phụ đề YouTube.'));
          }
        };
      });
    },

    async handleDownload(format) {
      const cues = await this.fetchSubtitles();
      const safeTitle = (this.getTitle() || 'youtube_subtitles').replace(/[/\\?%*:|"<>]/g, '_');
      let content = '';
      let filename = `${safeTitle}.${format}`;
      let mimeType = 'text/plain;charset=utf-8;';

      if (format === 'srt') {
        content = PARSER ? PARSER.toSRT(cues) : '';
        mimeType = 'application/x-subrip;charset=utf-8;';
      } else if (format === 'vtt') {
        content = PARSER ? PARSER.toWebVTT(cues) : '';
        mimeType = 'text/vtt;charset=utf-8;';
      } else if (format === 'txt') {
        content = PARSER ? PARSER.toReadableTranscript(cues) : '';
      }

      this.download(content, filename, mimeType);
    },

    download(content, filename, mimeType = 'text/plain;charset=utf-8;') {
      const blob = new Blob([content], { type: mimeType });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }
  };

  // Runtime message listener for Popup & Studio
  chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (msg.action === 'get_media_info') {
      sendResponse({
        success: true,
        platform: 'youtube',
        title: YouTubeManager.getTitle(),
        url: window.location.href,
        hasTracks: YouTubeManager.tracks && YouTubeManager.tracks.length > 0,
        selectedTrack: YouTubeManager.selectedTrack ? {
          label: YouTubeManager.selectedTrack.label || 'English'
        } : null
      });
      return false;
    }

    if (msg.action === 'download_subtitles') {
      YouTubeManager.handleDownload(msg.format || 'srt').then(() => {
        sendResponse({ success: true });
      }).catch((err) => {
        sendResponse({ success: false, error: err.message });
      });
      return true;
    }

    if (msg.action === 'get_subtitles') {
      YouTubeManager.fetchSubtitles().then((cues) => {
        sendResponse({
          success: true,
          platform: 'youtube',
          title: YouTubeManager.getTitle(),
          url: window.location.href,
          cues: cues
        });
      }).catch((err) => {
        sendResponse({ success: false, error: err.message });
      });
      return true;
    }
  });

  YouTubeManager.init();
})();
