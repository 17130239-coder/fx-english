/**
 * FX English - YouTube Content Script
 * Manages floating widget on player, subtitle downloads (.SRT, .VTT, .TXT),
 * and in-page POS vocabulary categorizer (Nouns, Verbs, Adj, Adv).
 */

(function () {
  'use strict';

  if (window.__fxYoutubeContentInjected) return;
  window.__fxYoutubeContentInjected = true;

  const PARSER = (typeof APP_SUBTITLE_PARSER !== 'undefined') ? APP_SUBTITLE_PARSER : null;

  const YouTubeManager = {
    tracks: [],
    selectedTrack: null,
    videoTitle: '',
    currentVideoId: '',
    cues: [],
    analysis: null,
    widgetEl: null,
    modalEl: null,
    activePosFilter: 'all',
    isLoadingSubtitles: false,

    init() {
      this.createWidget();
      this.listenBridge();
      this.checkVideoChange();
      this.pollUrlChanges();
    },

    getVideoId() {
      try {
        const u = new URL(window.location.href);
        if (u.searchParams.has('v')) return u.searchParams.get('v');
        const match = u.pathname.match(/\/shorts\/([a-zA-Z0-9_-]+)/);
        if (match) return match[1];
        const embedMatch = u.pathname.match(/\/embed\/([a-zA-Z0-9_-]+)/);
        if (embedMatch) return embedMatch[1];
      } catch (e) {}
      return null;
    },

    getTitle() {
      return this.videoTitle ||
        document.querySelector('h1.ytd-watch-metadata yt-formatted-string, #title h1, h1.title')?.textContent?.trim() ||
        document.title.replace(' - YouTube', '').trim() ||
        'YouTube Video';
    },

    listenBridge() {
      // Injected MAIN world script bridge event
      window.addEventListener('fx_youtube_bridge_event', (e) => {
        const { type, data } = e.detail || {};
        if (type === 'youtube_tracks_ready' && data) {
          if (data.title && !this.videoTitle) this.videoTitle = data.title;
          if (Array.isArray(data.tracks) && data.tracks.length > 0 && this.tracks.length === 0) {
            this.tracks = data.tracks;
            if (!this.selectedTrack) {
              this.selectedTrack = this.tracks.find(t => t.isEnglish && !t.isAutoGenerated) ||
                                  this.tracks.find(t => t.isEnglish) ||
                                  this.tracks[0];
            }
            this.updateWidget();
            this.updateTrackSelectOptions();
          }
        }
      });
    },

    async checkVideoChange() {
      const vid = this.getVideoId();
      if (!vid) return;

      if (vid !== this.currentVideoId) {
        this.currentVideoId = vid;
        this.cues = [];
        this.analysis = null;
        this.tracks = [];
        this.selectedTrack = null;
        this.updateWidget();

        await this.loadVideoTracks();
      }
    },

    pollUrlChanges() {
      let lastUrl = window.location.href;
      setInterval(() => {
        if (window.location.href !== lastUrl) {
          lastUrl = window.location.href;
          this.checkVideoChange();
        }
      }, 1000);

      window.addEventListener('yt-navigate-finish', () => {
        setTimeout(() => this.checkVideoChange(), 600);
      });
    },

    async loadVideoTracks() {
      const vid = this.getVideoId();
      if (!vid) return;

      const badge = document.getElementById('fx-yt-widget-badge');
      if (badge) {
        badge.textContent = 'Đang tìm CC...';
        badge.classList.remove('active');
      }

      try {
        const res = await new Promise((resolve) => {
          chrome.runtime.sendMessage({
            action: 'fetch_youtube_captions',
            videoId: vid
          }, resolve);
        });

        if (res && res.success) {
          if (res.title) this.videoTitle = res.title;
          if (Array.isArray(res.tracks) && res.tracks.length > 0) {
            this.tracks = res.tracks;
            this.selectedTrack = res.selectedTrack || this.tracks[0];
            if (Array.isArray(res.cues) && res.cues.length > 0) {
              this.cues = res.cues;
            }
          }
          this.updateWidget();
          this.updateTrackSelectOptions();
        } else {
          // Ask injected script as fallback
          window.dispatchEvent(new CustomEvent('fx_youtube_request_info'));
        }
      } catch (err) {
        window.dispatchEvent(new CustomEvent('fx_youtube_request_info'));
      }
    },

    createWidget() {
      if (this.widgetEl) return;
      this.widgetEl = document.createElement('div');
      this.widgetEl.id = 'fx-youtube-widget';
      this.widgetEl.innerHTML = `
        <button class="fx-widget-pill" title="FX English - Tải phụ đề & Tách từ vựng">
          <span class="fx-widget-icon">⚡ FX</span>
          <span class="fx-widget-title">Phụ đề & Từ vựng</span>
          <span class="fx-widget-badge" id="fx-yt-widget-badge">Đang tìm...</span>
        </button>
      `;

      const appendTarget = document.querySelector('#movie_player, .html5-video-player') || document.body;
      appendTarget.appendChild(this.widgetEl);
      this.widgetEl.querySelector('.fx-widget-pill').onclick = () => this.openModal();
    },

    updateWidget() {
      if (!this.widgetEl) this.createWidget();
      const badge = document.getElementById('fx-yt-widget-badge');
      if (!badge) return;
      if (this.selectedTrack) {
        badge.textContent = this.selectedTrack.label || 'English';
        badge.classList.add('active');
      } else {
        badge.textContent = 'Bật CC';
        badge.classList.remove('active');
      }
    },

    updateTrackSelectOptions() {
      const select = document.getElementById('fx-select-track');
      if (!select) return;

      if (!this.tracks || this.tracks.length === 0) {
        select.innerHTML = '<option value="">(Không có phụ đề cho video này)</option>';
        return;
      }

      select.innerHTML = this.tracks.map((t, idx) => `
        <option value="${idx}" ${t === this.selectedTrack ? 'selected' : ''}>${this.escape(t.label)}</option>
      `).join('');

      const btnAnalyze = document.getElementById('fx-btn-analyze');
      if (btnAnalyze) btnAnalyze.disabled = false;
    },

    async fetchSubtitles(forceTrackIndex = null) {
      if (this.cues.length > 0 && forceTrackIndex === null) {
        return this.cues;
      }

      const videoId = this.getVideoId();
      if (!videoId) {
        throw new Error('Không xác định được video ID từ đường dẫn YouTube.');
      }

      this.isLoadingSubtitles = true;
      try {
        const res = await new Promise((resolve) => {
          chrome.runtime.sendMessage({
            action: 'fetch_youtube_captions',
            videoId: videoId,
            trackIndex: (typeof forceTrackIndex === 'number') ? forceTrackIndex : (this.selectedTrack ? this.selectedTrack.index : undefined)
          }, resolve);
        });

        this.isLoadingSubtitles = false;

        if (res && res.success && Array.isArray(res.cues) && res.cues.length > 0) {
          if (res.title) this.videoTitle = res.title;
          if (res.tracks && res.tracks.length > 0) this.tracks = res.tracks;
          if (res.selectedTrack) this.selectedTrack = res.selectedTrack;
          this.cues = res.cues;
          this.updateWidget();
          this.updateTrackSelectOptions();
          return this.cues;
        }

        // Secondary fallback: Direct fetch from selectedTrack.baseUrl
        if (this.selectedTrack && this.selectedTrack.baseUrl) {
          let rawText = '';
          try {
            const resp = await fetch(this.selectedTrack.baseUrl);
            if (resp.ok) rawText = await resp.text();
          } catch (e) {}

          if (!rawText) {
            const fb = await new Promise((resolve) => {
              chrome.runtime.sendMessage({ action: 'fetch_external_url', url: this.selectedTrack.baseUrl }, resolve);
            });
            if (fb && fb.success) rawText = fb.text;
          }

          if (rawText && PARSER) {
            const parsedCues = PARSER.parse(rawText);
            if (parsedCues && parsedCues.length > 0) {
              this.cues = parsedCues;
              return this.cues;
            }
          }
        }

        throw new Error(res?.error || 'Video này không có phụ đề tiếng Anh.');
      } catch (err) {
        this.isLoadingSubtitles = false;
        throw err;
      }
    },

    openModal() {
      if (!this.modalEl) {
        this.modalEl = document.createElement('div');
        this.modalEl.id = 'fx-youtube-modal-backdrop';
        this.modalEl.className = 'fx-modal-backdrop';
        document.body.appendChild(this.modalEl);
      }

      const title = this.getTitle();
      const hasTrack = Boolean(this.selectedTrack || (this.tracks && this.tracks.length > 0));

      this.modalEl.innerHTML = `
        <div class="fx-modal-card">
          <div class="fx-modal-header">
            <div class="fx-modal-title-group">
              <span class="fx-modal-tag">🔴 FX YouTube English</span>
              <h2 class="fx-modal-title">${this.escape(title)}</h2>
            </div>
            <button class="fx-modal-close" id="fx-modal-btn-close">&times;</button>
          </div>

          <div class="fx-modal-body">
            <div class="fx-track-bar">
              <label class="fx-field-label">Kênh phụ đề:</label>
              <select id="fx-select-track" class="fx-select">
                ${(this.tracks || []).map((t, idx) => `
                  <option value="${idx}" ${t === this.selectedTrack ? 'selected' : ''}>${this.escape(t.label)}</option>
                `).join('')}
                ${(!this.tracks || this.tracks.length === 0) ? '<option value="">(Đang tải danh sách phụ đề...)</option>' : ''}
              </select>
            </div>

            <div class="fx-actions-row">
              <button id="fx-btn-analyze" class="fx-btn fx-btn-primary" ${!hasTrack ? 'disabled' : ''}>
                <span>⚡ Tách từ vựng (POS: Danh, Động, Tính, Trạng)</span>
              </button>

              <div class="fx-dl-group">
                <button id="fx-btn-dl-srt" class="fx-btn fx-btn-outline" title="Tải file .SRT">⬇ .SRT</button>
                <button id="fx-btn-dl-vtt" class="fx-btn fx-btn-outline" title="Tải file .VTT">⬇ .VTT</button>
                <button id="fx-btn-dl-txt" class="fx-btn fx-btn-outline" title="Tải transcript .TXT">⬇ .TXT</button>
              </div>

              <button id="fx-btn-open-studio" class="fx-btn fx-btn-secondary" title="Mở Studio">
                <span>Mở Studio ↗</span>
              </button>
            </div>

            <div id="fx-modal-loading" class="fx-loading-state" style="display:none;">
              <div class="fx-spinner"></div>
              <span id="fx-loading-text">Đang phân tích từ vựng...</span>
            </div>

            <div id="fx-analysis-results" class="fx-analysis-results" style="display:none;">
              <div class="fx-pos-tabs">
                <button class="fx-pos-tab active" data-pos="all">Tất cả (<span id="fx-count-all">0</span>)</button>
                <button class="fx-pos-tab" data-pos="noun">📘 Danh từ (<span id="fx-count-noun">0</span>)</button>
                <button class="fx-pos-tab" data-pos="verb">📙 Động từ (<span id="fx-count-verb">0</span>)</button>
                <button class="fx-pos-tab" data-pos="adjective">📗 Tính từ (<span id="fx-count-adj">0</span>)</button>
                <button class="fx-pos-tab" data-pos="adverb">📕 Trạng từ (<span id="fx-count-adv">0</span>)</button>
              </div>

              <div class="fx-search-bar">
                <input type="text" id="fx-search-input" placeholder="Tìm kiếm từ vựng hoặc nghĩa tiếng Việt...">
                <button id="fx-btn-export-anki" class="fx-btn-sm fx-btn-anki">🗂️ Xuất Anki</button>
                <button id="fx-btn-export-csv" class="fx-btn-sm fx-btn-csv">📊 Xuất CSV</button>
              </div>

              <div id="fx-words-grid" class="fx-words-grid"></div>
            </div>
          </div>
        </div>
      `;

      this.modalEl.style.display = 'flex';

      document.getElementById('fx-modal-btn-close').onclick = () => { this.modalEl.style.display = 'none'; };
      this.modalEl.onclick = (e) => { if (e.target === this.modalEl) this.modalEl.style.display = 'none'; };

      const trackSelect = document.getElementById('fx-select-track');
      if (trackSelect) {
        trackSelect.onchange = async () => {
          const idx = parseInt(trackSelect.value, 10);
          if (!isNaN(idx) && this.tracks[idx]) {
            this.selectedTrack = this.tracks[idx];
            this.cues = [];
            this.analysis = null;
            this.updateWidget();
            try {
              await this.fetchSubtitles(idx);
            } catch (e) {
              console.warn(e);
            }
          }
        };
      }

      document.getElementById('fx-btn-dl-srt').onclick = () => this.handleDownload('srt');
      document.getElementById('fx-btn-dl-vtt').onclick = () => this.handleDownload('vtt');
      document.getElementById('fx-btn-dl-txt').onclick = () => this.handleDownload('txt');
      document.getElementById('fx-btn-analyze').onclick = () => this.runVocabularyAnalysis();

      document.getElementById('fx-btn-open-studio').onclick = () => {
        chrome.storage.local.set({
          fxPendingStudio: {
            title: this.getTitle(),
            url: window.location.href,
            cues: this.cues,
            analysis: this.analysis
          }
        }, () => {
          chrome.runtime.sendMessage({ action: 'open_studio' });
        });
      };

      if (this.analysis) {
        this.renderAnalysisResults(this.analysis);
      } else if (!this.tracks || this.tracks.length === 0) {
        this.loadVideoTracks();
      }
    },

    async runVocabularyAnalysis() {
      const loadingEl = document.getElementById('fx-modal-loading');
      const loadingText = document.getElementById('fx-loading-text');
      const resultsEl = document.getElementById('fx-analysis-results');

      try {
        loadingEl.style.display = 'flex';
        loadingText.textContent = 'Đang tải phụ đề tiếng Anh từ YouTube...';

        const cues = await this.fetchSubtitles();
        loadingText.textContent = `Đang phân loại ${cues.length} câu phụ đề theo 4 loại từ...`;

        const response = await new Promise((resolve, reject) => {
          chrome.runtime.sendMessage({
            action: 'analyze_subtitles',
            cues: cues,
            options: { videoTitle: this.getTitle(), videoUrl: window.location.href }
          }, (res) => {
            if (chrome.runtime.lastError) reject(new Error(chrome.runtime.lastError.message));
            else if (res && res.success) resolve(res.analysis);
            else reject(new Error(res?.error || 'Phân tích thất bại'));
          });
        });

        this.analysis = response;
        loadingEl.style.display = 'none';
        resultsEl.style.display = 'block';
        this.renderAnalysisResults(response);
      } catch (err) {
        loadingEl.style.display = 'none';
        alert(err.message || 'Lỗi khi phân tích từ vựng');
      }
    },

    renderAnalysisResults(analysis) {
      if (!analysis) return;
      const { summary, posGroups, allWords } = analysis;

      document.getElementById('fx-count-all').textContent = summary.uniqueWords || allWords.length;
      document.getElementById('fx-count-noun').textContent = summary.nounCount || posGroups.nouns.length;
      document.getElementById('fx-count-verb').textContent = summary.verbCount || posGroups.verbs.length;
      document.getElementById('fx-count-adj').textContent = summary.adjCount || posGroups.adjectives.length;
      document.getElementById('fx-count-adv').textContent = summary.advCount || posGroups.adverbs.length;

      const tabs = document.querySelectorAll('.fx-pos-tab');
      tabs.forEach((tab) => {
        tab.onclick = () => {
          tabs.forEach(t => t.classList.remove('active'));
          tab.classList.add('active');
          this.activePosFilter = tab.getAttribute('data-pos');
          this.filterAndRenderWords(analysis);
        };
      });

      const searchInput = document.getElementById('fx-search-input');
      if (searchInput) {
        searchInput.oninput = () => this.filterAndRenderWords(analysis);
      }

      document.getElementById('fx-btn-export-anki').onclick = () => this.exportVocab('anki', analysis);
      document.getElementById('fx-btn-export-csv').onclick = () => this.exportVocab('csv', analysis);

      this.filterAndRenderWords(analysis);
    },

    filterAndRenderWords(analysis) {
      const grid = document.getElementById('fx-words-grid');
      if (!grid) return;

      let words = [];
      if (this.activePosFilter === 'all') words = analysis.allWords || [];
      else if (this.activePosFilter === 'noun') words = analysis.posGroups.nouns || [];
      else if (this.activePosFilter === 'verb') words = analysis.posGroups.verbs || [];
      else if (this.activePosFilter === 'adjective') words = analysis.posGroups.adjectives || [];
      else if (this.activePosFilter === 'adverb') words = analysis.posGroups.adverbs || [];

      const query = (document.getElementById('fx-search-input')?.value || '').toLowerCase().trim();
      if (query) {
        words = words.filter(w =>
          w.word.toLowerCase().includes(query) ||
          (w.translation && w.translation.toLowerCase().includes(query)) ||
          (w.vietnamese && w.vietnamese.toLowerCase().includes(query))
        );
      }

      grid.innerHTML = '';
      if (words.length === 0) {
        grid.innerHTML = '<div class="fx-empty-msg">Không tìm thấy từ vựng phù hợp.</div>';
        return;
      }

      words.forEach((item) => {
        const card = document.createElement('div');
        card.className = 'fx-word-card';

        const posName = item.posLabelVi || item.pos;
        const firstCtx = (item.contexts && item.contexts[0]) ? item.contexts[0] : null;

        let contextHtml = '';
        if (firstCtx && (firstCtx.sentence || firstCtx.text)) {
          const s = firstCtx.sentence || firstCtx.text;
          const reg = new RegExp(`\\b(${item.word})\\b`, 'gi');
          const highlighted = this.escape(s).replace(reg, '<b>$1</b>');
          const timeSec = firstCtx.startSec || 0;
          const timeDisplay = firstCtx.startTime || (PARSER ? PARSER.formatDisplayTime(timeSec) : '00:00');

          contextHtml = `
            <div class="fx-word-context">
              <span class="fx-context-text">"${highlighted}"</span>
              <button class="fx-btn-seek" data-time="${timeSec}">▶ ${timeDisplay}</button>
            </div>
          `;
        }

        card.innerHTML = `
          <div class="fx-word-header">
            <span class="fx-word-text">${this.escape(item.word)}</span>
            <span class="fx-pos-badge ${item.pos}">${posName}</span>
            <span class="fx-freq-pill">${item.frequency}x</span>
            <button class="fx-btn-speak" title="Phát âm">🔊</button>
          </div>
          <div class="fx-word-ipa">
            ${item.ipa || ''}
            ${item.cefr ? `<span class="fx-cefr-tag">${item.cefr}</span>` : ''}
          </div>
          <div class="fx-word-trans">${this.escape(item.translation || item.vietnamese || 'Đang cập nhật...')}</div>
          ${contextHtml}
        `;

        card.querySelector('.fx-btn-speak').onclick = (e) => {
          e.stopPropagation();
          this.speak(item.word);
        };

        const seekBtn = card.querySelector('.fx-btn-seek');
        if (seekBtn) {
          seekBtn.onclick = (e) => {
            e.stopPropagation();
            const time = parseFloat(seekBtn.dataset.time);
            this.seekTo(time);
          };
        }

        grid.appendChild(card);
      });
    },

    seekTo(seconds) {
      window.dispatchEvent(new CustomEvent('fx_youtube_seek', {
        detail: { seconds }
      }));
    },

    speak(text) {
      try {
        window.speechSynthesis.cancel();
        const u = new SpeechSynthesisUtterance(text);
        u.lang = 'en-US';
        window.speechSynthesis.speak(u);
      } catch (e) {}
    },

    async handleDownload(format) {
      try {
        const cues = await this.fetchSubtitles();
        const safeTitle = (this.getTitle() || 'youtube_subtitles').replace(/[/\\?%*:|"<>]/g, '_');
        let content = '';
        let filename = `${safeTitle}.${format}`;
        let mimeType = 'text/plain;charset=utf-8;';

        if (format === 'srt') {
          content = PARSER ? PARSER.toSRT(cues) : '';
          mimeType = 'application/x-subrip;charset=utf-8;';
        } else if (format === 'vtt') {
          content = PARSER ? PARSER.toWebVTT(cues) : '';
          mimeType = 'text/vtt;charset=utf-8;';
        } else if (format === 'txt') {
          content = PARSER ? PARSER.toReadableTranscript(cues) : '';
        }

        this.download(content, filename, mimeType);
      } catch (err) {
        alert(err.message || 'Không thể tải file phụ đề');
      }
    },

    exportVocab(format, analysis) {
      let words = [];
      if (this.activePosFilter === 'all') words = analysis.allWords || [];
      else if (this.activePosFilter === 'noun') words = analysis.posGroups.nouns || [];
      else if (this.activePosFilter === 'verb') words = analysis.posGroups.verbs || [];
      else if (this.activePosFilter === 'adjective') words = analysis.posGroups.adjectives || [];
      else if (this.activePosFilter === 'adverb') words = analysis.posGroups.adverbs || [];

      chrome.runtime.sendMessage({
        action: 'export_vocab',
        words: words,
        format: format,
        title: this.getTitle()
      }, (res) => {
        if (res && res.success && res.content) {
          this.download(res.content, res.filename, res.mime);
        } else {
          alert('Lỗi khi xuất file');
        }
      });
    },

    download(content, filename, mimeType = 'text/plain;charset=utf-8;') {
      const blob = new Blob([content], { type: mimeType });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    },

    escape(str) {
      if (!str) return '';
      return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
    }
  };

  // Runtime message listener for Popup
  chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (msg.action === 'get_media_info') {
      sendResponse({
        success: true,
        platform: 'youtube',
        title: YouTubeManager.getTitle(),
        hasTracks: YouTubeManager.tracks && YouTubeManager.tracks.length > 0,
        selectedTrack: YouTubeManager.selectedTrack ? {
          label: YouTubeManager.selectedTrack.label || 'English'
        } : null
      });
      return false;
    }

    if (msg.action === 'open_vocab_modal') {
      YouTubeManager.openModal();
      sendResponse({ success: true });
      return false;
    }

    if (msg.action === 'download_subtitles') {
      YouTubeManager.handleDownload(msg.format || 'srt').then(() => {
        sendResponse({ success: true });
      }).catch((err) => {
        sendResponse({ success: false, error: err.message });
      });
      return true;
    }
  });

  YouTubeManager.init();
})();
